export interface Briefing {
  title: string;
  markdown: string;
  csv: string | null;
  csvFileName: string | null;
  /** The length of the text that will be shared; 0 when no section is chosen (nothing to share). */
  characters: number;
  lineCount: number;
}

export interface BriefingContext {
  today: DateKey;
  unit: WeightUnit;
}

const NO_SECTION_LINE = 'Choose at least one section.';
const LAST_DAYS = 14;

const STRENGTH_LINE =
  "- Strength: volume = sum of weight × reps over every logged set (Lyfta's tick is ignored). Estimated 1-rep max uses Epley, only from sets of 1–12 reps. Bodyweight exercises (best weight 0) have no 1-rep max or PR lines.";
const ADHERENCE_LINE =
  '- Adherence: a scheduled session counts as done when Lyfta marks it complete or a workout was logged that day. A session scheduled today and not yet done is "not yet done", not missed.';
const MISSING_DATA_LINE =
  '- Missing data: "–" means no data for that day. A missing day is missing, not zero, and is left out of every average and total; each line says how many days it used.';

/** Ruling 13: the sections that will be written. A single workout offers only Body and Sleep. */
export function sectionsEnabled(request: ExportRequest): SectionId[] {
  const chosen = SECTION_IDS.filter((id) => request.sections[id]);
  return request.preset === 'workout'
    ? chosen.filter((id) => id === 'body' || id === 'sleep')
    : chosen;
}

/** 'About 1,900 characters', with ' + CSV' when a CSV goes with it; '—' when there is no text. */
export function sizeLabel(b: Briefing): string {
  if (b.characters === 0) return '—';
  const rounded = Math.max(100, Math.round(b.characters / 100) * 100);
  return `About ${formatInteger(rounded)} characters${b.csv !== null ? ' + CSV' : ''}`;
}

function quoteLines(starter: string): string[] {
  return starter
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .map((line) => `> ${line}`);
}

function withYear(date: DateKey, other: DateKey): string {
  const year = parseDateKey(date).year;
  return year === parseDateKey(other).year
    ? formatShortDate(date)
    : `${formatShortDate(date)} ${year}`;
}

function rangeText(window: DateWindow): string {
  return `${withYear(window.from, window.to)} – ${formatShortDate(window.to)} ${parseDateKey(window.to).year}`;
}

function periodLine(view: PeriodView): string {
  const base = `- Period: ${rangeText(view.window)} (${view.days} days).`;
  if (view.previous === null) return base;
  if (view.preset !== 'journey') return `${base} Compared with ${rangeText(view.previous)}.`;
  const lastFrom = addDays(view.window.to, -6);
  return `${base} Compared: first 7 days of the journey against the last 7 days (${rangeText(view.previous)} against ${rangeText({ from: lastFrom, to: view.window.to })}).`;
}

function commonLines(prep: Prepared, ctx: BriefingContext): string[] {
  const person = personLine(prep, ctx.today, ctx.unit);
  return [
    ...(person === null ? [] : [person]),
    `- Units: weights in ${ctx.unit}, distances in ${distanceUnit(ctx.unit)}.`,
    MISSING_DATA_LINE,
    `- Generated by Health Hub on ${ctx.today} from the owner's own data. This is not medical advice.`,
  ];
}

/** Joins blocks of lines with one blank line between them and no double blanks anywhere. */
function joinBlocks(blocks: readonly (readonly string[])[]): string[] {
  const out: string[] = [];
  for (const block of blocks) {
    if (block.length === 0) continue;
    if (out.length > 0) out.push('');
    out.push(...block);
  }
  return out;
}

function finish(lines: readonly string[]): string {
  const cleaned: string[] = [];
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (line === '' && (cleaned.length === 0 || cleaned[cleaned.length - 1] === '')) continue;
    cleaned.push(line);
  }
  while (cleaned[cleaned.length - 1] === '') cleaned.pop();
  return `${cleaned.join('\n')}\n`;
}

function dedupe(lines: readonly string[]): string[] {
  return lines.filter((line, index) => lines.indexOf(line) === index);
}

function sectionText(id: SectionId, prep: Prepared, view: PeriodView): SectionText {
  switch (id) {
    case 'body':
      return buildBodySection(prep, view);
    case 'workouts': {
      const text = buildTrainingSection(prep, view);
      return { ...text, context: [STRENGTH_LINE, ADHERENCE_LINE] };
    }
    case 'activity':
      return buildActivitySection(prep, view);
    case 'sleep':
      return buildSleepSection(prep, view);
    case 'heartRate':
      return buildHeartRateSection(prep, view);
  }
}

/** Whether a section has anything to show in the window (tables are skipped when it has not). */
function hasData(id: SectionId, prep: Prepared, window: DateWindow): boolean {
  switch (id) {
    case 'body':
      return prep.readings.some((r) => inWindow(r.date, window));
    case 'workouts':
      return prep.data.workouts.some((w) => inWindow(localDateKey(w.performedAt), window));
    case 'activity': {
      const days = activityByDate(prep);
      return datesIn(window).some((date) => {
        const day = days.get(date);
        return day !== undefined && (day.steps !== null || day.distanceM !== null);
      });
    }
    case 'sleep':
      return nightsIn(prep, window).length > 0;
    case 'heartRate': {
      const days = heartRateByDate(prep);
      return datesIn(window).some((date) => days.has(date));
    }
  }
}

function dailySections(enabled: readonly SectionId[]): DailySections {
  return {
    activity: enabled.includes('activity'),
    sleep: enabled.includes('sleep'),
    heartRate: enabled.includes('heartRate'),
  };
}

/** 'Activity, sleep and heart rate', or the subset that is switched on. */
function dailyHeading(daily: DailySections, suffix: string): string {
  const names = [
    ...(daily.activity ? ['activity'] : []),
    ...(daily.sleep ? ['sleep'] : []),
    ...(daily.heartRate ? ['heart rate'] : []),
  ];
  const joined =
    names.length > 1 ? `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}` : names[0];
  return `### ${(joined as string).charAt(0).toUpperCase()}${(joined as string).slice(1)} — ${suffix}`;
}

function lastDays(view: PeriodView): DateWindow {
  const from = addDays(view.window.to, -(LAST_DAYS - 1));
  return { from: from < view.window.from ? view.window.from : from, to: view.window.to };
}

function weeklyAggregates(
  prep: Prepared,
  view: PeriodView,
  enabled: readonly SectionId[],
): string[] {
  const parts = enabled.map((id) => {
    switch (id) {
      case 'body':
        return bodyWeeklyColumns(prep, view);
      case 'workouts':
        return trainingWeeklyColumns(prep, view);
      case 'activity':
        return activityWeeklyColumns(prep, view);
      case 'sleep':
        return sleepWeeklyColumns(prep, view);
      case 'heartRate':
        return heartRateWeeklyColumns(prep, view);
    }
  });
  const headers = ['Week of', ...parts.flatMap((part) => part.headers)];
  const rows = weekStartsIn(view.window).map((week) => [
    weekLabel(week, view),
    ...parts.flatMap((part) => part.byWeek.get(week) ?? part.headers.map(() => MISSING)),
  ]);
  return ['### Weekly aggregates', ...mdTable(headers, rows)];
}

function detailBlocks(
  prep: Prepared,
  view: PeriodView,
  enabled: readonly SectionId[],
  texts: ReadonlyMap<SectionId, SectionText>,
): string[][] {
  const daily = dailySections(enabled);
  const dailyEnabled = (['activity', 'sleep', 'heartRate'] as const).filter((id) =>
    enabled.includes(id),
  );
  const dailyHasData = (window: DateWindow): boolean =>
    dailyEnabled.some((id) => hasData(id, prep, window));
  const body = texts.get('body')?.detail ?? [];
  const training = texts.get('workouts')?.detail ?? [];
  const todayNote = ['* today: the day is not over yet.'];
  const bodyHasToday = body.some((line) =>
    line.startsWith(`| ${dayLabel(view.today, view.today)} |`),
  );
  const showDailyTable = (window: DateWindow): boolean => dailyHasData(window);
  // Only the daily table (not the weekly one) carries the "* today" footnote.
  const dailyShowsFootnote = (window: DateWindow): boolean =>
    view.level !== 'medium' &&
    showDailyTable(window) &&
    (daily.activity || daily.heartRate) &&
    window.to >= view.today;
  const bodyBlock = (window: DateWindow): string[] =>
    body.length === 0
      ? []
      : bodyHasToday && !dailyShowsFootnote(window)
        ? [...body, '', ...todayNote]
        : body;

  if (view.level === 'long') {
    const window = lastDays(view);
    const blocks: string[][] = [];
    const anyData = enabled.some((id) => hasData(id, prep, view.window));
    if (anyData) blocks.push(weeklyAggregates(prep, view, enabled));
    const recent: string[][] = [];
    if (bodyBlock(window).length > 0) recent.push(bodyBlock(window));
    if (showDailyTable(window)) {
      recent.push([
        dailyHeading(daily, `last ${LAST_DAYS} days`),
        ...buildDailyActivityTable(prep, view, window, daily),
      ]);
    }
    if (recent.length > 0) blocks.push([`### Last ${LAST_DAYS} days`], ...recent);
    return blocks;
  }

  const blocks: string[][] = [];
  if (bodyBlock(view.window).length > 0) blocks.push(bodyBlock(view.window));
  if (training.length > 0) blocks.push(training);
  if (showDailyTable(view.window)) {
    blocks.push(
      view.level === 'full'
        ? [dailyHeading(daily, 'daily'), ...buildDailyActivityTable(prep, view, view.window, daily)]
        : [dailyHeading(daily, 'weekly'), ...buildPeriodTable(prep, view, daily)],
    );
  }
  return blocks;
}

function buildWorkoutBriefing(
  prep: Prepared,
  request: ExportRequest,
  ctx: BriefingContext,
): string {
  const parts = buildSingleWorkout(prep, request, ctx);
  const quote = quoteLines(request.starter);
  if (parts === null) {
    return finish(['# Single workout', '', '- This workout is no longer stored.']);
  }
  return finish(
    joinBlocks([
      [parts.title],
      quote,
      ['## Context', '', ...parts.context, ...commonLines(prep, ctx), STRENGTH_LINE],
      ['## Summary', '', ...parts.summary],
      ['## Detail', '', ...parts.detail],
    ]),
  );
}

function titleOf(markdown: string): string {
  const first = markdown.split('\n')[0] ?? '';
  return first.replace(/^#\s*/, '');
}

function done(markdown: string, csv: { fileName: string; content: string } | null): Briefing {
  return {
    title: titleOf(markdown),
    markdown,
    csv: csv?.content ?? null,
    csvFileName: csv?.fileName ?? null,
    characters: markdown.length,
    lineCount: markdown.trimEnd().split('\n').length,
  };
}

/** The Markdown briefing (and the journey CSV), built from stored data only. Nothing is logged. */
export function buildBriefing(
  data: ExportData,
  request: ExportRequest,
  context: BriefingContext,
): Briefing {
  const prep = prepareExportData(data);
  if (request.preset === 'workout') return done(buildWorkoutBriefing(prep, request, context), null);

  const view = resolvePeriod({
    request,
    today: context.today,
    unit: context.unit,
    firstDataDate: earliestDataDate(data),
  }) as PeriodView;
  const title = periodTitle(request.preset, view.window);
  const enabled = sectionsEnabled(request);
  if (enabled.length === 0) {
    return { ...done(finish([title, '', NO_SECTION_LINE]), null), characters: 0 };
  }

  const texts = new Map(enabled.map((id) => [id, sectionText(id, prep, view)] as const));
  const sections = enabled.map((id) => texts.get(id) as SectionText);
  const contextLines = [
    periodLine(view),
    ...commonLines(prep, context),
    ...dedupe(sections.flatMap((section) => section.context)),
  ];
  const summaryBlocks = sections.map((section) => section.summary);
  const detail = detailBlocks(prep, view, enabled, texts);

  const markdown = finish(
    joinBlocks([
      [title],
      quoteLines(request.starter),
      ['## Context', '', ...contextLines],
      ['## Summary', '', ...joinBlocks(summaryBlocks)],
      detail.length === 0 ? [] : ['## Detail', '', ...joinBlocks(detail)],
    ]),
  );
  const wantsCsv =
    request.preset === 'journey' && request.includeCsv && earliestDataDate(data) !== null;
  return done(markdown, wantsCsv ? buildJourneyCsv(prep, view) : null);
}
